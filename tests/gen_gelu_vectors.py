"""Generate deterministic GELU Q8 test vectors."""

import math
import random
from pathlib import Path

SEED = 530
RANDOM_CASES = 64

COEFF_0044715_Q24 = 750193
COEFF_SQRT_2_OVER_PI_Q24 = 13386282


def round_shift_away(value, shift):
    """Round right shift to nearest, with ties away from zero."""
    half = 1 << (shift - 1)

    if value >= 0:
        return (value + half) >> shift

    return -(((-value) + half) >> shift)


def make_lut():
    """Generate the 65-entry positive tanh LUT in Q15."""
    return [
        math.floor(math.tanh(i / 16.0) * 32768 + 0.5)
        for i in range(65)
    ]


TANH_LUT = make_lut()


def tanh_q15(z_q24):
    """Approximate tanh(Q24) and return signed Q15."""
    limit = 4 << 24
    step = 1 << 20

    sign = -1 if z_q24 < 0 else 1
    magnitude = abs(z_q24)

    if magnitude >= limit:
        return sign * TANH_LUT[64]

    index = magnitude >> 20
    remainder = magnitude & (step - 1)

    lower = TANH_LUT[index]
    upper = TANH_LUT[index + 1]

    delta = (upper - lower) * remainder
    interpolated = lower + round_shift_away(delta, 20)

    return sign * interpolated


def gelu_q8(x_q8):
    """Calculate GELU using the agreed fixed-point implementation."""

    if x_q8 >= 1024:
        return x_q8

    if x_q8 <= -1024:
        return 0

    x_q24 = x_q8 * 65536

    x2_q24 = round_shift_away(x_q24 * x_q24, 24)
    x3_q24 = round_shift_away(x2_q24 * x_q24, 24)

    cubic_term = round_shift_away(
        COEFF_0044715_Q24 * x3_q24, 24
    )

    inner_q24 = x_q24 + cubic_term

    z_q24 = round_shift_away(
        COEFF_SQRT_2_OVER_PI_Q24 * inner_q24, 24
    )

    tanh_value_q15 = tanh_q15(z_q24)

    numerator = x_q8 * (32768 + tanh_value_q15)

    return round_shift_away(numerator, 16)


def make_cases():
    """Create directed and deterministic random test cases."""
    directed = [
        -1536, -1024, -768, -512, -256, -128, -1,
        0,
        1, 128, 256, 512, 768, 1023, 1024, 1536,
    ]

    cases = [
        (f"directed_{i}", x, gelu_q8(x))
        for i, x in enumerate(directed)
    ]

    rng = random.Random(SEED)

    for i in range(RANDOM_CASES):
        x = rng.randint(-1023, 1023)
        cases.append((f"random_{i}", x, gelu_q8(x)))

    return cases


def main():
    cases = make_cases()

    output = [
        "// Generated by tests/gen_gelu_vectors.py. Do not edit.\n",
        "#ifndef GELU_VECTORS_H\n",
        "#define GELU_VECTORS_H\n\n",
        "#include <stdint.h>\n\n",
        "typedef struct {\n",
        "    const char *name;\n",
        "    int32_t input_q8;\n",
        "    int32_t expected_q8;\n",
        "} gelu_case_t;\n\n",
        "static const gelu_case_t gelu_cases[] = {\n",
    ]

    for name, x, expected in cases:
        output.append(
            f'    {{"{name}", {x}, {expected}}},\n'
        )

    output.extend([
        "};\n\n",
        f"#define GELU_NCASES {len(cases)}\n\n",
        "#endif\n",
    ])

    root = Path(__file__).resolve().parents[1]
    destination = root / "tests" / "vectors" / "gelu_vectors.h"

    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("".join(output))

    print("Generated:", destination)
    print("Number of cases:", len(cases))
    print("LUT entries:", len(TANH_LUT))
    print("First LUT entry:", TANH_LUT[0])
    print("Last LUT entry:", TANH_LUT[-1])


if __name__ == "__main__":
    main()
