"""Generate int8 test vectors and their expected dot products (pure Python, no C involved)."""
import random

SIZES = [16, 64, 256, 1024]
SEED = 530


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def make_cases():
    rng = random.Random(SEED)
    cases = []
    for n in SIZES:
        a = [rng.randint(-128, 127) for _ in range(n)]
        b = [rng.randint(-128, 127) for _ in range(n)]
        cases.append((f"rand_{n}", a, b))
    cases.append(("min_1024", [-128] * 1024, [-128] * 1024))   # largest possible sum
    cases.append(("neg_1024", [-128] * 1024, [127] * 1024))    # most negative sum
    return cases


def c_array(name, values):
    body = ", ".join(str(v) for v in values)
    return f"static const int8_t {name}[{len(values)}] __attribute__((aligned(4))) = {{{body}}};\n"


def main():
    cases = make_cases()
    out = ["// Generated by tests/gen_dot_vectors.py. Do not edit.\n#include <stdint.h>\n\n"]
    for name, a, b in cases:
        out.append(c_array(f"a_{name}", a))
        out.append(c_array(f"b_{name}", b))
    out.append("\ntypedef struct { const char *name; int n; const int8_t *a, *b; int32_t expected; } dot_case_t;\n")
    out.append("static const dot_case_t dot_cases[] = {\n")
    for name, a, b in cases:
        out.append(f'    {{"{name}", {len(a)}, a_{name}, b_{name}, {dot(a, b)}}},\n')
    out.append("};\n")
    out.append(f"#define DOT_NCASES {len(cases)}\n")
    with open("tests/vectors/dot_vectors.h", "w") as f:
        f.write("".join(out))
    for name, a, b in cases:
        print(name, dot(a, b))


if __name__ == "__main__":
    main()
